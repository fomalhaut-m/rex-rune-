/**
 * 内置字库取模。
 * - 不传 width/height：使用 size 指定的尺寸（默认 5x7）。
 * - 传 width/height：把 size 的内置字库缩放到目标尺寸。
 *
 * 大于 8×8 的尺寸建议走 cnToGlyphs（上传 ttf/otf 字体）路径，
 * 避免手写字库的数据维护问题。
 */
export function asciiToGlyphs(text: string, opts: AsciiOptions = {}): GlyphResult {
  const { size = '5x7', width, height, negative = true } = opts;
  const builtin = ASCII_BUILTIN[size];
  const srcW = builtin.width;
  const srcH = builtin.height;
  const srcData = builtin.data;
  const dstW = width ?? srcW;
  const dstH = height ?? srcH;

  const bytes = text.split('').map((ch) => {
    const code = ch.charCodeAt(0);
    const src = srcData[code] ?? srcData[0x20];
    // 缩放 srcW×srcH → dstW×dstH（最近邻）
    const pixels = new Uint8Array(dstW * dstH);
    for (let y = 0; y < dstH; y++) {
      for (let x = 0; x < dstW; x++) {
        const sx = Math.min(srcW - 1, Math.floor((x * srcW) / dstW));
        const sy = Math.min(srcH - 1, Math.floor((y * srcH) / dstH));
        // 5x7 字库是 col-major，bit0=顶；8x8 字库是 col-major，bit7=顶。
        const byte = src[sx];
        const bit =
          size === '5x7' ? (byte >> sy) & 1 : (byte >> (7 - sy)) & 1;
        pixels[y * dstW + x] = bit ? 0 : 255;
      }
    }
    return bitmapToBytes(pixels, dstW, dstH, 128, negative);
  });
  return { bytes, width: dstW, height: dstH };
}

/* ============ 汉字取模（浏览器字体） ============ */
export interface CnBrowserOptions {
  /** CSS font-family，可写系统栈如 "PingFang SC", "Microsoft YaHei", sans-serif */
  fontFamily?: string;
  /** CSS font-weight，如 400 / 700 / "bold" */
  fontWeight?: number | string;
  /** 字符单元宽（像素） */
  width?: number;
  /** 字符单元高（像素） */
  height?: number;
  /** 字号（像素），默认等于 height */
  fontSize?: number;
  /** 字间距（像素） */
  gap?: number;
  /** 是否阴码（默认 true，亮点=1） */
  negative?: boolean;
  /** 灰度阈值 0-255（默认 128） */
  threshold?: number;
}

/**
 * 用浏览器内置字体（Canvas2D fillText）渲染字符串后逐字取模。
 * 无需上传字体文件，结果取决于用户系统/浏览器提供的字体。
 */
export function cnToGlyphsByBrowser(text: string, opts: CnBrowserOptions = {}): GlyphResult {
  const {
    fontFamily = 'sans-serif',
    fontWeight = 400,
    width,
    height,
    fontSize,
    gap = 0,
    negative = true,
    threshold = 128,
  } = opts;

  const chars = Array.from(text);
  const cellW = width ?? fontSize ?? 32;
  const cellH = height ?? fontSize ?? 32;
  const size = fontSize ?? cellH;

  // 整张画布拼接所有字符
  const canvas = document.createElement('canvas');
  canvas.width = chars.length * (cellW + gap);
  canvas.height = cellH;
  const ctx = canvas.getContext('2d');
  if (!ctx) return { bytes: [], width: 0, height: 0 };

  ctx.fillStyle = '#fff';
  ctx.fillRect(0, 0, canvas.width, canvas.height);
  ctx.fillStyle = '#000';
  ctx.textBaseline = 'middle';
  ctx.textAlign = 'center';
  ctx.font = `${fontWeight} ${size}px ${fontFamily}`;

  chars.forEach((_, i) => {
    const cx = i * (cellW + gap) + cellW / 2;
    const cy = cellH / 2;
    ctx.fillText(chars[i], cx, cy);
  });

  const img = ctx.getImageData(0, 0, canvas.width, canvas.height);
  const bytes: number[][] = [];
  for (let i = 0; i < chars.length; i++) {
    const cellPixels = new Uint8Array(cellW * cellH);
    for (let y = 0; y < cellH; y++) {
      for (let x = 0; x < cellW; x++) {
        const px = i * (cellW + gap) + x;
        const idx = (y * canvas.width + px) * 4;
        const r = img.data[idx];
        const g = img.data[idx + 1];
        const b = img.data[idx + 2];
        cellPixels[y * cellW + x] = (r * 299 + g * 587 + b * 114) / 1000;
      }
    }
    bytes.push(bitmapToBytes(cellPixels, cellW, cellH, threshold, negative));
  }
  return { bytes, width: cellW, height: cellH };
}

/* ============ 汉字取模（opentype.js） ============ */
export interface CnOptions {
  /** opentype.js 解析后的 Font 实例 */
  font: OTFont;
  /** 字符单元宽（像素），默认按 fontSize 自适应 */
  width?: number;
  /** 字符单元高（像素），默认按 fontSize 自适应 */
  height?: number;
  /** 字号（像素，决定栅格化精度） */
  fontSize?: number;
  /** 字间距（像素） */
  gap?: number;
  /** 是否阴码（默认 true，亮点=1） */
  negative?: boolean;
}

/**
 * 用 opentype.js 把字符串渲染为位图，再逐字取模
 * 流程：font.getPath → 提取贝塞尔路径 → Canvas 栅格化 → bitmapToBytes
 */
export function cnToGlyphs(text: string, opts: CnOptions): GlyphResult {
  const { font, width, height, negative = true, fontSize, gap = 0 } = opts;
  if (!font) return { bytes: [], width: 0, height: 0 };

  const chars = Array.from(text);
  const cellW = width ?? fontSize ?? 32;
  const cellH = height ?? fontSize ?? 32;

  // 整张画布拼接所有字符的 path
  const canvas = document.createElement('canvas');
  canvas.width = chars.length * (cellW + gap);
  canvas.height = cellH;
  const ctx = canvas.getContext('2d');
  if (!ctx) return { bytes: [], width: 0, height: 0 };

  ctx.fillStyle = '#fff';
  ctx.fillRect(0, 0, canvas.width, canvas.height);

  chars.forEach((ch, i) => {
    const glyph = font.charToGlyph(ch);
    const path = glyph.getPath(0, 0, fontSize ?? cellH);
    const bb = path.getBoundingBox();
    if (!bb || bb.x2 - bb.x1 === 0) return;

    // 单字符子画布
    const sub = document.createElement('canvas');
    sub.width = cellW;
    sub.height = cellH;
    const subCtx = sub.getContext('2d')!;
    subCtx.fillStyle = '#fff';
    subCtx.fillRect(0, 0, cellW, cellH);
    subCtx.fillStyle = '#000';

    // 等比缩放到 cellW/cellH 内，居中
    const glyphW = bb.x2 - bb.x1;
    const glyphH = bb.y2 - bb.y1;
    const drawScale = Math.min(cellW / glyphW, cellH / glyphH) * 0.9;
    const drawX = (cellW - glyphW * drawScale) / 2 - bb.x1 * drawScale;
    const drawY = (cellH - glyphH * drawScale) / 2 - bb.y1 * drawScale;

    subCtx.setTransform(drawScale, 0, 0, drawScale, drawX, drawY);
    path.draw(subCtx);
    subCtx.setTransform(1, 0, 0, 1, 0, 0);

    ctx.drawImage(sub, i * (cellW + gap), 0);
  });

  const img = ctx.getImageData(0, 0, canvas.width, canvas.height);
  const bytes: number[][] = [];
  for (let i = 0; i < chars.length; i++) {
    const cellPixels = new Uint8Array(cellW * cellH);
    for (let y = 0; y < cellH; y++) {
      for (let x = 0; x < cellW; x++) {
        const px = i * (cellW + gap) + x;
        const idx = (y * canvas.width + px) * 4;
        const r = img.data[idx];
        const g = img.data[idx + 1];
        const b = img.data[idx + 2];
        cellPixels[y * cellW + x] = (r * 299 + g * 587 + b * 114) / 1000;
      }
    }
    bytes.push(bitmapToBytes(cellPixels, cellW, cellH, 128, negative));
  }
  return { bytes, width: cellW, height: cellH };
}

/* ============ 加载 opentype 字体 ============ */
/**
 * 从 File 或 URL 加载 opentype 字体
 */
export async function loadFont(src: File | string): Promise<OTFont> {
  if (typeof src === 'string') {
    return opentype.load(src);
  }
  const buffer = await src.arrayBuffer();
  return opentype.parse(buffer);
}

/* ============ 图片取模 ============ */
export type ImageMode = 'mono' | 'rgb565';

export interface ImageOptions {
  mode: ImageMode;
  /** mono 模式阈值 0-255（默认 128） */
  threshold?: number;
  /** 目标宽度（像素），0=按原图 */
  targetWidth?: number;
  /** 目标高度（像素），0=按原图 */
  targetHeight?: number;
  /** 是否使用 Floyd-Steinberg 抖动（仅 mono 模式有效） */
  dither?: boolean;
}

export interface ImageGlyphResult {
  bytes: number[];
  width: number;
  height: number;
  /** 每像素字节数（mono=1，rgb565=2） */
  bytesPerPixel: number;
}

/**
 * 加载图片（Promise 包装）
 */
export function loadImage(file: File | string): Promise<HTMLImageElement> {
  return new Promise((resolve, reject) => {
    const img = new Image();
    img.crossOrigin = 'anonymous';
    img.onload = () => resolve(img);
    img.onerror = () => reject(new Error('图片加载失败'));
    if (typeof file === 'string') {
      img.src = file;
    } else {
      img.src = URL.createObjectURL(file);
    }
  });
}

function imageToImageData(img: HTMLImageElement, w: number, h: number): ImageData {
  const canvas = document.createElement('canvas');
  canvas.width = w;
  canvas.height = h;
  const ctx = canvas.getContext('2d');
  if (!ctx) throw new Error('Canvas 2D context unavailable');
  ctx.imageSmoothingEnabled = false;
  ctx.drawImage(img, 0, 0, w, h);
  return ctx.getImageData(0, 0, w, h);
}

/**
 * Floyd-Steinberg 抖动：把灰度图变成纯黑白（视觉上保留更多细节）
 */
function applyFloydSteinberg(gray: Uint8Array, width: number, height: number, threshold: number): void {
  for (let y = 0; y < height; y++) {
    for (let x = 0; x < width; x++) {
      const idx = y * width + x;
      const old = gray[idx];
      const newVal = old < threshold ? 0 : 255;
      const err = old - newVal;
      gray[idx] = newVal;
      if (x + 1 < width) gray[idx + 1] += (err * 7) / 16;
      if (y + 1 < height) {
        if (x - 1 >= 0) gray[idx + width - 1] += (err * 3) / 16;
        gray[idx + width] += (err * 5) / 16;
        if (x + 1 < width) gray[idx + width + 1] += (err * 1) / 16;
      }
    }
  }
}

/**
 * 图片取模：mono（单色，含可选抖动）或 rgb565（原色）
 */
export async function imageToGlyph(
  file: File | string,
  opts: ImageOptions,
): Promise<ImageGlyphResult> {
  const { mode, threshold = 128, targetWidth = 0, targetHeight = 0, dither = false } = opts;
  const img = await loadImage(file);
  const w = targetWidth || img.naturalWidth;
  const h = targetHeight || img.naturalHeight;
  const data = imageToImageData(img, w, h);

  if (mode === 'mono') {
    const pixels = new Uint8Array(w * h);
    for (let i = 0; i < pixels.length; i++) {
      const r = data.data[i * 4];
      const g = data.data[i * 4 + 1];
      const b = data.data[i * 4 + 2];
      pixels[i] = (r * 299 + g * 587 + b * 114) / 1000;
    }
    if (dither) applyFloydSteinberg(pixels, w, h, threshold);
    return {
      bytes: bitmapToBytes(pixels, w, h, threshold, true),
      width: w,
      height: h,
      bytesPerPixel: 1,
    };
  }

  // RGB565：大端，R5 G6 B5
  const out = new Array<number>(w * h * 2);
  let idx = 0;
  for (let i = 0; i < w * h; i++) {
    const r = data.data[i * 4];
    const g = data.data[i * 4 + 1];
    const b = data.data[i * 4 + 2];
    const rgb565 = ((r & 0xF8) << 8) | ((g & 0xFC) << 3) | (b >> 3);
    out[idx++] = (rgb565 >> 8) & 0xff;
    out[idx++] = rgb565 & 0xff;
  }
  return { bytes: out, width: w, height: h, bytesPerPixel: 2 };
}

/* ============ 格式化输出 ============ */
/**
 * 字符数组 → C 数组字面量（每字符一行）
 */
export function formatCArray(bytes: number[][]): string {
  return bytes
    .map((row) => '  ' + row.map((b) => `0x${b.toString(16).toUpperCase().padStart(2, '0')}`).join(','))
    .join(',\n');
}

/**
 * 连续字节数组 → C 数组字面量（每行 cols 个）
 */
export function formatImageCArray(bytes: number[], cols = 16): string {
  const lines: string[] = [];
  for (let i = 0; i < bytes.length; i += cols) {
    const chunk = bytes.slice(i, i + cols);
    lines.push('  ' + chunk.map((b) => `0x${b.toString(16).toUpperCase().padStart(2, '0')}`).join(','));
  }
  return lines.join(',\n');
}

/* ============ 预览 ============ */
/**
 * 单色字节数组 → Canvas 预览（白底黑点）
 */
export function bytesToCanvas(
  bytes: number[],
  width: number,
  height: number,
  scale = 4,
): HTMLCanvasElement {
  const canvas = document.createElement('canvas');
  canvas.width = width * scale;
  canvas.height = height * scale;
  const ctx = canvas.getContext('2d');
  if (!ctx) return canvas;
  ctx.fillStyle = '#fff';
  ctx.fillRect(0, 0, canvas.width, canvas.height);
  ctx.fillStyle = '#000';
  const bytesPerRow = Math.ceil(width / 8);
  for (let y = 0; y < height; y++) {
    for (let x = 0; x < width; x++) {
      const b = bytes[y * bytesPerRow + Math.floor(x / 8)] ?? 0;
      const bit = (b >> (7 - (x % 8))) & 1;
      if (bit) ctx.fillRect(x * scale, y * scale, scale, scale);
    }
  }
  return canvas;
}

/**
 * RGB565 → Canvas 预览
 */
export function rgb565ToCanvas(
  bytes: number[],
  width: number,
  height: number,
  scale = 1,
): HTMLCanvasElement {
  const canvas = document.createElement('canvas');
  canvas.width = width * scale;
  canvas.height = height * scale;
  const ctx = canvas.getContext('2d');
  if (!ctx) return canvas;
  const img = ctx.createImageData(width, height);
  for (let i = 0; i < width * height; i++) {
    const rgb565 = (bytes[i * 2] << 8) | bytes[i * 2 + 1];
    const r = ((rgb565 >> 11) & 0x1f) << 3;
    const g = ((rgb565 >> 5) & 0x3f) << 2;
    const b = (rgb565 & 0x1f) << 3;
    img.data[i * 4] = r | (r >> 5);
    img.data[i * 4 + 1] = g | (g >> 6);
    img.data[i * 4 + 2] = b | (b >> 5);
    img.data[i * 4 + 3] = 255;
  }
  ctx.putImageData(img, 0, 0);
  if (scale > 1) {
    const big = document.createElement('canvas');
    big.width = width * scale;
    big.height = height * scale;
    const bctx = big.getContext('2d');
    if (bctx) {
      bctx.imageSmoothingEnabled = false;
      bctx.drawImage(canvas, 0, 0, big.width, big.height);
      return big;
    }
  }
  return canvas;
}