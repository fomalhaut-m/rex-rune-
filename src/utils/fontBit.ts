/* 内置尺寸字典 */
const ASCII_BUILTIN = {
  '5x7': { width: 5, height: 7, data: ASCII_5x7 },
  '8x8': { width: 8, height: 8, data: ASCII_8x8 },
} as const;

export type AsciiSize = keyof typeof ASCII_BUILTIN;

/* ============ 通用类型 ============ */
export interface AsciiOptions {
  /** 内置尺寸：5x7 或 8x8（默认 5x7） */
  size?: AsciiSize;
  /** 自定义目标尺寸（覆盖 size）。优先于 size。 */
  width?: number;
  height?: number;
  /** 是否阴码（默认 true，亮点=1） */
  negative?: boolean;
}

export interface GlyphResult {
  /** 每个字符的字节数组（col-major，宽 ceil(W/8) × 高 字节） */
  bytes: number[][];
  /** 字符宽度像素 */
  width: number;
  /** 字符高度像素 */
  height: number;
}

/* ============ 核心位图→字节转换 ============ */
/**
 * 把灰度位图转成字节数组（col-major）
 * @param pixels 灰度数组（0=白 255=黑）
 * @param width 位图宽度
 * @param height 位图高度
 * @param threshold 阈值（像素值 < threshold 视为亮点）
 * @param negative 阴码（true）/阳码（false）
 */
export function bitmapToBytes(
  pixels: Uint8Array,
  width: number,
  height: number,
  threshold = 128,
  negative = true,
): number[] {
  const bytesPerRow = Math.ceil(width / 8);
  const out = new Array<number>(bytesPerRow * height).fill(0);

  for (let y = 0; y < height; y++) {
    for (let x = 0; x < width; x++) {
      const idx = y * width + x;
      const lit = pixels[idx] < threshold;
      const bit = negative ? (lit ? 1 : 0) : (lit ? 0 : 1);
      const rowByteIndex = y * bytesPerRow + Math.floor(x / 8);
      const bitIndex = 7 - (x % 8);
      out[rowByteIndex] |= bit << bitIndex;
    }
  }
  return out;
}

